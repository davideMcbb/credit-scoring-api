"""Export the scorecard estimated in the credit-scoring project to this service.

Usage (from this repository):
    python tools/export_scorecard.py ../credit-scoring

It rebuilds the final scorecard exactly as the Python project does, then writes
  - src/main/resources/db/migration/V2__scorecard_1_0.sql   (the scorecard as data)
  - src/test/resources/golden_cases.csv                      (expected results for all 1,000 loans)
The Java tests check that the service gives the same score, probability of default,
decision and reasons as the Python code for every loan.
"""
import sys
from pathlib import Path

import numpy as np

SOURCE = Path(sys.argv[1]).resolve()
HERE = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(SOURCE))

from credit_scoring import data as D  # noqa: E402
from credit_scoring.pipeline import fit_scorecard  # noqa: E402

VERSION = "1.0"
AVG_DECIMALS = 6

df = D.load()
dev_i, _ = D.stratified_split(df["bad"].values)
dev = df.iloc[dev_i].reset_index(drop=True)
fit = fit_scorecard(dev)
card = fit.card
codes = D.read_codetable()


def q(text: str) -> str:
    return "'" + text.replace("'", "''") + "'"


# average points of each characteristic on the development sample: the reference for reasons
idx_dev = card.attribute_index(dev)
average = {v: round(float(card.points[v][idx_dev[:, j]].mean()), AVG_DECIMALS)
           for j, v in enumerate(card.variables)}

sql = [
    f"-- Scorecard {VERSION}, generated by tools/export_scorecard.py from the credit-scoring project.",
    "-- Estimated on 700 development loans of the South German Credit data (CC BY 4.0).",
    "",
    "INSERT INTO scorecard (id, version, description, pdo, base_score, base_odds, factor, offset_points,",
    "                       population_bad_rate, cutoff, active)",
    f"VALUES (1, {q(VERSION)}, {q('Logistic scorecard, 10 characteristics, cutoff for a 5% bad rate and 5:1 costs')},",
    f"        20, 600, 50, {float(card.factor):.12f}, {float(card.offset):.12f}, {D.POP_BAD_RATE}, {fit.cutoff_population}, TRUE);",
    "",
]
attr_id = 0
attr_rows, code_rows, char_rows = [], [], []
for pos, v in enumerate(card.variables, start=1):
    b = card.binnings[v]
    kind = "NUMERIC" if b.kind == "numeric" else "CATEGORICAL"
    char_rows.append(f"({pos}, 1, {q(v)}, {pos}, {q(kind)}, {card.neutral_points(v):.0f}, {average[v]})")
    labels = b.labels(codes.get(v), "en")
    for k in range(b.k):
        attr_id += 1
        upper = "NULL"
        if kind == "NUMERIC" and k < len(b.edges):
            upper = f"{b.edges[k]:.4f}"
        attr_rows.append(f"({attr_id}, {pos}, {k + 1}, {q(labels[k])}, {upper}, {int(card.points[v][k])})")
        if kind == "CATEGORICAL":
            code_rows.extend(f"({attr_id}, {c})" for c in b.groups[k])

sql += ["INSERT INTO scorecard_characteristic (id, scorecard_id, name, position, kind, neutral_points, average_points)",
        "VALUES " + ",\n       ".join(char_rows) + ";", ""]
sql += ["INSERT INTO scorecard_attribute (id, characteristic_id, position, label, upper_bound, points)",
        "VALUES " + ",\n       ".join(attr_rows) + ";", ""]
sql += ["INSERT INTO scorecard_attribute_code (attribute_id, code)",
        "VALUES " + ",\n       ".join(code_rows) + ";", ""]
for t in ("scorecard", "scorecard_characteristic", "scorecard_attribute"):
    sql.append(f"SELECT setval(pg_get_serial_sequence('{t}', 'id'), (SELECT max(id) FROM {t}));")
out_sql = HERE / "src/main/resources/db/migration" / "V2__scorecard_1_0.sql"
out_sql.write_text("\n".join(sql) + "\n", encoding="utf-8")

# expected results for every loan, with the same rules as the service
scores = card.score(df)
idx = card.attribute_index(df)
lines = ["row," + ",".join(card.variables) + ",score,pd,approved,reason_1,reason_2,reason_3"]
for i in range(len(df)):
    lost = []
    for j, v in enumerate(card.variables):
        pts = card.points[v][idx[i, j]] if idx[i, j] >= 0 else card.neutral_points(v)
        lost.append(average[v] - float(pts))
    order = np.argsort(-np.array(lost), kind="stable")
    reasons = ([card.variables[k] for k in order if lost[k] > 0] + ["", "", ""])[:3]
    pd_ = float(card.pd_population(scores[i]))
    values = ",".join(str(int(df[v].iloc[i])) for v in card.variables)
    approved = str(bool(scores[i] >= fit.cutoff_population)).lower()
    lines.append(f"{i + 1},{values},{int(scores[i])},{pd_:.12f},{approved},{','.join(reasons)}")
(HERE / "src/test/resources/golden_cases.csv").write_text("\n".join(lines) + "\n", encoding="utf-8")
print(f"{out_sql.name}: {len(char_rows)} characteristics, {attr_id} attributes, {len(code_rows)} codes")
print(f"golden_cases.csv: {len(df)} loans, approved {sum(s >= fit.cutoff_population for s in scores)}")
