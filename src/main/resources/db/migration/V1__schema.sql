-- A scorecard is stored as data, so a new version is a new set of rows and every
-- scored application keeps a reference to the version that scored it.

CREATE TABLE scorecard (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    version             VARCHAR(20)    NOT NULL UNIQUE,
    description         VARCHAR(200)   NOT NULL,
    pdo                 INTEGER        NOT NULL CHECK (pdo > 0),
    base_score          INTEGER        NOT NULL,
    base_odds           INTEGER        NOT NULL CHECK (base_odds > 0),
    factor              NUMERIC(18, 12) NOT NULL CHECK (factor > 0),
    offset_points       NUMERIC(18, 12) NOT NULL,
    population_bad_rate NUMERIC(6, 4)  NOT NULL CHECK (population_bad_rate > 0 AND population_bad_rate < 1),
    cutoff              NUMERIC(8, 2)  NOT NULL,
    active              BOOLEAN        NOT NULL DEFAULT FALSE,
    created_at          TIMESTAMPTZ    NOT NULL DEFAULT now()
);

-- at most one active scorecard
CREATE UNIQUE INDEX scorecard_one_active ON scorecard (active) WHERE active;

CREATE TABLE scorecard_characteristic (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    scorecard_id   BIGINT        NOT NULL REFERENCES scorecard (id),
    name           VARCHAR(40)   NOT NULL,
    position       INTEGER       NOT NULL,
    kind           VARCHAR(12)   NOT NULL CHECK (kind IN ('NUMERIC', 'CATEGORICAL')),
    neutral_points INTEGER       NOT NULL,
    average_points NUMERIC(10, 6) NOT NULL,
    UNIQUE (scorecard_id, name),
    UNIQUE (scorecard_id, position)
);

-- one row per class; upper_bound is inclusive and NULL for the last numeric class
CREATE TABLE scorecard_attribute (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    characteristic_id BIGINT        NOT NULL REFERENCES scorecard_characteristic (id),
    position          INTEGER       NOT NULL,
    label             VARCHAR(120)  NOT NULL,
    upper_bound       NUMERIC(14, 4),
    points            INTEGER       NOT NULL,
    UNIQUE (characteristic_id, position)
);

-- the input codes that fall into each class of a categorical characteristic
CREATE TABLE scorecard_attribute_code (
    attribute_id BIGINT  NOT NULL REFERENCES scorecard_attribute (id),
    code         INTEGER NOT NULL,
    PRIMARY KEY (attribute_id, code)
);

CREATE TABLE credit_application (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    public_id             UUID          NOT NULL UNIQUE,
    created_at            TIMESTAMPTZ   NOT NULL,
    scorecard_id          BIGINT        NOT NULL REFERENCES scorecard (id),
    duration_months       INTEGER       NOT NULL CHECK (duration_months BETWEEN 1 AND 120),
    amount                INTEGER       NOT NULL CHECK (amount > 0),
    age                   INTEGER       NOT NULL CHECK (age BETWEEN 18 AND 100),
    employment_duration   VARCHAR(30)   NOT NULL,
    installment_rate      VARCHAR(30)   NOT NULL,
    checking_account      VARCHAR(30)   NOT NULL,
    credit_history        VARCHAR(30)   NOT NULL,
    purpose               VARCHAR(30)   NOT NULL,
    savings               VARCHAR(30)   NOT NULL,
    other_debtors         VARCHAR(30)   NOT NULL,
    score                 INTEGER       NOT NULL,
    probability_of_default NUMERIC(10, 8) NOT NULL CHECK (probability_of_default BETWEEN 0 AND 1),
    decision              VARCHAR(10)   NOT NULL CHECK (decision IN ('APPROVE', 'REJECT'))
);

CREATE INDEX credit_application_created ON credit_application (created_at);
CREATE INDEX credit_application_decision ON credit_application (decision, created_at);

-- points given to each characteristic: the audit trail of how the score was built
CREATE TABLE credit_application_points (
    application_id  BIGINT       NOT NULL REFERENCES credit_application (id) ON DELETE CASCADE,
    line            INTEGER      NOT NULL,
    characteristic  VARCHAR(40)  NOT NULL,
    input_value     INTEGER      NOT NULL,
    attribute_label VARCHAR(120) NOT NULL,
    points          INTEGER      NOT NULL,
    PRIMARY KEY (application_id, line)
);

-- up to three characteristics that lower the score most against the average applicant
CREATE TABLE credit_application_reason (
    application_id       BIGINT        NOT NULL REFERENCES credit_application (id) ON DELETE CASCADE,
    reason_rank          INTEGER       NOT NULL CHECK (reason_rank BETWEEN 0 AND 2),
    characteristic       VARCHAR(40)   NOT NULL,
    points_below_average NUMERIC(10, 6) NOT NULL,
    PRIMARY KEY (application_id, reason_rank)
);
